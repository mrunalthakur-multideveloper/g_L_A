def ensure_table_exists(conn, table_name: str = "links"):
    """Creates the public.links table and indexes in Neon DB if not present."""
    if not conn:
        return
    try:
        with conn.cursor() as cur:
            cur.execute(CREATE_LINKS_TABLE_SQL)
    except Exception as e:
        print(f"ℹ️ Notice checking table schema: {e}")


