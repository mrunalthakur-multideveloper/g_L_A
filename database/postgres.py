def save_jobs_to_neon(
    records: Any,
    table_name: str = "links",
    batch_size: int = 100
) -> int:
    """
    Stores verified postings into Neon PostgreSQL public.links using execute_values.
    
    CRITICAL - Prevent Batch Collision:
      Before executing the SQL upsert, strictly deduplicate the records in memory by job_id:
      df_sql = df.drop_duplicates(subset=["job_id"]).copy()
      (This avoids PostgreSQL aborting with: ON CONFLICT DO UPDATE command cannot affect row a second time)
    """
    conn = get_neon_connection()
    if not conn:
        return 0

    ensure_table_exists(conn, table_name)
    total_saved = 0

    # In-memory deduplication by job_id using pandas drop_duplicates
    raw_deduped_records: List[Dict[str, Any]] = []
    try:
        import pandas as pd
        if isinstance(records, pd.DataFrame):
            df_sql = records.drop_duplicates(subset=["job_id"]).copy()
            raw_deduped_records = [format_job_for_sql_upsert(r) for r in df_sql.to_dict(orient="records")]
        else:
            formatted_list = [format_job_for_sql_upsert(r) for r in records if r]
            if formatted_list:
                df = pd.DataFrame(formatted_list)
                df_sql = df.drop_duplicates(subset=["job_id"]).copy()
                raw_deduped_records = df_sql.to_dict(orient="records")
    except Exception:
        seen_ids = set()
        for r in records:
            fmt = format_job_for_sql_upsert(r)
            jid = fmt.get("job_id")
            if jid and jid not in seen_ids:
                seen_ids.add(jid)
                raw_deduped_records.append(fmt)

    tuples = [to_tuple_record(r) for r in raw_deduped_records if r.get("job_id")]
    if not tuples:
        return 0

    # Full table qualified name
    full_table = f"public.{table_name}" if "." not in table_name else table_name

    upsert_sql = f"""
    INSERT INTO {full_table} (
        job_id, title, company_name, company_url, company_logo,
        location_city, location_state, location_country, location_display,
        description, date_posted, scraped_at, job_url, apply_url,
        job_type, job_level, company_industry, job_function,
        is_remote, is_easy_apply, compensation_min, compensation_max,
        compensation_currency, compensation_interval, emails,
        search_keyword, experience, salary_text, created_at,
        skills, sponsorship_h1b, source, experience_min, experience_max
    ) VALUES %s
    ON CONFLICT (job_id) DO UPDATE SET
        title = COALESCE(EXCLUDED.title, {full_table}.title),
        company_name = COALESCE(EXCLUDED.company_name, {full_table}.company_name),
        company_url = COALESCE(EXCLUDED.company_url, {full_table}.company_url),
        company_logo = COALESCE(EXCLUDED.company_logo, {full_table}.company_logo),
        location_city = COALESCE(EXCLUDED.location_city, {full_table}.location_city),
        location_state = COALESCE(EXCLUDED.location_state, {full_table}.location_state),
        location_country = COALESCE(EXCLUDED.location_country, {full_table}.location_country),
        location_display = COALESCE(EXCLUDED.location_display, {full_table}.location_display),
        description = COALESCE(EXCLUDED.description, {full_table}.description),
        scraped_at = EXCLUDED.scraped_at,
        apply_url = COALESCE(EXCLUDED.apply_url, {full_table}.apply_url),
        job_type = COALESCE(EXCLUDED.job_type, {full_table}.job_type),
        job_level = COALESCE(EXCLUDED.job_level, {full_table}.job_level),
        company_industry = COALESCE(EXCLUDED.company_industry, {full_table}.company_industry),
        job_function = COALESCE(EXCLUDED.job_function, {full_table}.job_function),
        is_remote = EXCLUDED.is_remote,
        is_easy_apply = EXCLUDED.is_easy_apply,
        compensation_min = COALESCE(EXCLUDED.compensation_min, {full_table}.compensation_min),
        compensation_max = COALESCE(EXCLUDED.compensation_max, {full_table}.compensation_max),
        compensation_currency = COALESCE(EXCLUDED.compensation_currency, {full_table}.compensation_currency),
        compensation_interval = COALESCE(EXCLUDED.compensation_interval, {full_table}.compensation_interval),
        emails = COALESCE(EXCLUDED.emails, {full_table}.emails),
        search_keyword = COALESCE(EXCLUDED.search_keyword, {full_table}.search_keyword),
        experience = COALESCE(EXCLUDED.experience, {full_table}.experience),
        salary_text = COALESCE(EXCLUDED.salary_text, {full_table}.salary_text),
        skills = COALESCE(EXCLUDED.skills, {full_table}.skills),
        sponsorship_h1b = COALESCE(EXCLUDED.sponsorship_h1b, {full_table}.sponsorship_h1b),
        source = COALESCE(EXCLUDED.source, {full_table}.source),
        experience_min = COALESCE(EXCLUDED.experience_min, {full_table}.experience_min),
        experience_max = COALESCE(EXCLUDED.experience_max, {full_table}.experience_max);
    """

    try:
        with conn.cursor() as cur:
            for i in range(0, len(tuples), batch_size):
                batch = tuples[i:i + batch_size]
                try:
                    psycopg2.extras.execute_values(cur, upsert_sql, batch, page_size=len(batch))
                    total_saved += len(batch)
                except Exception as batch_err:
                    # Retry record by record for robust resilience
                    for single in batch:
                        try:
                            psycopg2.extras.execute_values(cur, upsert_sql, [single])
                            total_saved += 1
                        except Exception:
                            pass
        conn.close()
    except Exception as e:
        print(f"⚠️ Error executing batch upsert to Neon DB: {e}")
        try:
            conn.close()
        except Exception:
            pass

    return total_saved


def save_jobs_to_supabase_fallback(
    records: List[Dict[str, Any]],
    table_name: str = "links",
    batch_size: int = 50
) -> int:
    """Fallback to Supabase client if Neon connection string is not provided."""
    client = get_supabase_client()
    if not client:
        return 0

    total_saved = 0
    clean_table = table_name.split(".")[-1]

    for i in range(0, len(records), batch_size):
        batch = records[i:i + batch_size]
        try:
            result = client.table(clean_table).upsert(
                batch,
                on_conflict="job_id"
            ).execute()
            if result.data:
                total_saved += len(result.data)
        except Exception:
            for single in batch:
                try:
                    res = client.table(clean_table).upsert(single, on_conflict="job_id").execute()
                    if res.data:
                        total_saved += len(res.data)
                except Exception:
                    pass
        time.sleep(0.1)

    return total_saved


def save_jobs_to_database(
    jobs: List[NormalizedJob],
    table_name: str = "links",
    only_it: bool = True,
    batch_size: int = 100
) -> int:
    """
    Saves or upserts IT job links at once into Neon PostgreSQL table 'public.links'.
    Falls back to Supabase if NEON_DATABASE_URL is not configured.
    Strictly filters to IT jobs only (is_it_job=True) and excludes Non-IT jobs.
    """
    if not jobs:
        return 0

    target_jobs = [j for j in jobs if j.is_it_job] if only_it else jobs
    if not target_jobs:
        print("ℹ️ No IT jobs found to store. Non-IT jobs are strictly excluded from database.")
        return 0

    # Format all records into exact schema
    formatted_records = [format_job_for_links_table(j) for j in target_jobs if (j.job_id or j.id)]
    if not formatted_records:
        return 0

    # 1. Try Neon DB direct connection
    if NEON_DATABASE_URL:
        saved = save_jobs_to_neon(formatted_records, table_name=table_name, batch_size=batch_size)
        if saved > 0:
            return saved

    # 2. Fallback to Supabase if configured
    if SUPABASE_URL and SUPABASE_KEY:
        return save_jobs_to_supabase_fallback(formatted_records, table_name=table_name, batch_size=batch_size)

    print("ℹ️ Neither NEON_DATABASE_URL nor SUPABASE credentials configured. Skipped DB storage.")
    return 0


def get_database_domain_summary(table_name: str = "links") -> List[Dict[str, Any]]:
    """
    Queries the PostgreSQL / Supabase table to inspect and return all existing search_keywords / domains and counts.
    """
    conn = get_neon_connection()
    if conn:
        try:
            full_table = f"public.{table_name}" if "." not in table_name else table_name
            with conn.cursor() as cur:
                cur.execute(f"""
                    SELECT COALESCE(search_keyword, 'unspecified') as domain, COUNT(*) as count,
                           MIN(date_posted) as min_date, MAX(date_posted) as max_date,
                           COUNT(DISTINCT company_name) as companies_count
                    FROM {full_table}
                    GROUP BY search_keyword
                    ORDER BY count DESC;
                """)
                rows = cur.fetchall()
                results = []
                for row in rows:
                    results.append({
                        "domain": row[0],
                        "job_count": row[1],
                        "earliest_posted": str(row[2]) if row[2] else None,
                        "latest_posted": str(row[3]) if row[3] else None,
                        "companies_count": row[4]
                    })
                conn.close()
                return results
        except Exception as e:
            print(f"⚠️ Error querying domain summary from Neon DB: {e}")
            try:
                conn.close()
            except Exception:
                pass

    # Fallback to Supabase if configured
    client = get_supabase_client()
    if client:
        try:
            clean_table = table_name.split(".")[-1]
            res = client.table(clean_table).select("search_keyword, company_name, date_posted").execute()
            if res.data:
                from collections import Counter
                counts = Counter(r.get("search_keyword") or "unspecified" for r in res.data)
                return [{"domain": k, "job_count": v, "companies_count": 0} for k, v in counts.most_common()]
        except Exception as e:
            print(f"⚠️ Error querying domain summary from Supabase: {e}")

    return []


